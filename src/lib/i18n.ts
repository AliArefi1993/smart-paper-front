export type TranslationKey = keyof typeof translations.en;

export function getStoredLanguage(): AppLanguage {
  if (typeof window === "undefined") return "en";
  return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "fa" ? "fa" : "en";
}

export function setStoredLanguage(language: AppLanguage): void {
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  window.dispatchEvent(new CustomEvent("smart-paper-language-change"));
}

export function translate(language: AppLanguage, key: TranslationKey): string {
  return translations[language][key] ?? translations.en[key];
}

export function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}
